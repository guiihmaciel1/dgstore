    public function handle(): int
    {
        $existingCount = DollarCpRate::count();

        if ($existingCount > 30 && ! $this->option('force')) {
            $this->info("Já existem {$existingCount} registros no histórico. Use --force para sobrescrever.");

            return self::SUCCESS;
        }

        $rates = $this->getHistoricalRates();
        $inserted = 0;
        $skipped = 0;

        $this->info('Populando histórico de cotações do dólar CP...');
        $bar = $this->output->createProgressBar(count($rates));

        foreach ($rates as [$dateStr, $rate]) {
            $date = Carbon::parse($dateStr . ' 12:00:00');

            $exists = DollarCpRate::whereDate('fetched_at', $date->toDateString())->exists();

            if ($exists) {
                $skipped++;
                $bar->advance();

                continue;
            }

            DollarCpRate::create([
                'rate'       => $rate,
                'fetched_at' => $date,
            ]);

            $inserted++;
            $bar->advance();
        }

        $bar->finish();
        $this->newLine(2);
        $this->info("Concluído: {$inserted} registros inseridos, {$skipped} ignorados (já existiam).");
        $this->info('Total no banco: ' . DollarCpRate::count() . ' registros.');

        return self::SUCCESS;
    }
